-- Crear tabla datos_experimento para unir datos de inversor e irradiancia
CREATE TABLE IF NOT EXISTS datos_experimento (
    id INT AUTO_INCREMENT PRIMARY KEY,
    fecha_hora DATETIME NOT NULL,
    Vpv1 FLOAT DEFAULT 0,
    Vpv2 FLOAT DEFAULT 0,
    Ipv1 FLOAT DEFAULT 0,
    Ipv2 FLOAT DEFAULT 0,
    Vac1 FLOAT DEFAULT 0,
    Vac2 FLOAT DEFAULT 0,
    Vac3 FLOAT DEFAULT 0,
    Iac1 FLOAT DEFAULT 0,
    Iac2 FLOAT DEFAULT 0,
    Iac3 FLOAT DEFAULT 0,
    Fac1 FLOAT DEFAULT 0,
    Fac2 FLOAT DEFAULT 0,
    Fac3 FLOAT DEFAULT 0,
    Pac FLOAT DEFAULT 0,
    EnergyToday FLOAT DEFAULT 0,
    EnergyTotal FLOAT DEFAULT 0,
    HourTotal FLOAT DEFAULT 0,
    temperatura FLOAT DEFAULT 0,
    irradiancia FLOAT DEFAULT 0,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY unique_fecha_hora (fecha_hora),
    INDEX idx_fecha_hora (fecha_hora),
    INDEX idx_fecha_creacion (fecha_creacion)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
